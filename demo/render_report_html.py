#!/usr/bin/env python3
"""
Render SEPA-Eval markdown report into a polished HTML dashboard.

Usage:
  python demo/render_report_html.py
  python demo/render_report_html.py --input demo/output/report.md --output demo/output/report.html
"""

from __future__ import annotations

import argparse
import html
import json
import math
import re
from collections import defaultdict
from pathlib import Path


def _read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines()


def _find_section_ranges(lines: list[str]) -> dict[str, tuple[int, int]]:
    headers: list[tuple[int, str]] = []
    for i, line in enumerate(lines):
        if line.startswith("## "):
            headers.append((i, line.strip()))

    ranges: dict[str, tuple[int, int]] = {}
    for idx, (start, title) in enumerate(headers):
        end = headers[idx + 1][0] if idx + 1 < len(headers) else len(lines)
        ranges[title] = (start, end)
    return ranges


def _parse_md_table(section_lines: list[str]) -> list[dict[str, str]]:
    table_lines = [ln for ln in section_lines if ln.strip().startswith("|")]
    if len(table_lines) < 3:
        return []

    header = [c.strip() for c in table_lines[0].strip().strip("|").split("|")]
    rows: list[dict[str, str]] = []
    for ln in table_lines[2:]:
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if len(cells) != len(header):
            continue
        rows.append({header[i]: cells[i] for i in range(len(header))})
    return rows


def _to_float(value: str) -> float:
    try:
        return float(value)
    except Exception:
        return 0.0


def _to_int(value: str) -> int:
    try:
        return int(value)
    except Exception:
        return 0


def _parse_failure_taxonomy(section_lines: list[str]) -> dict[str, dict[str, int]]:
    data: dict[str, dict[str, int]] = {}
    current_model = ""
    model_re = re.compile(r"^\*\*(.+?)\*\*$")
    item_re = re.compile(r"^\s*-\s*([a-zA-Z0-9_]+):\s*(\d+)\s*$")

    for ln in section_lines:
        m = model_re.match(ln.strip())
        if m:
            current_model = m.group(1)
            data[current_model] = {}
            continue
        item = item_re.match(ln)
        if item and current_model:
            data[current_model][item.group(1)] = int(item.group(2))
    return data


def _parse_summary(section_lines: list[str]) -> dict[str, int]:
    out: dict[str, int] = {}
    rx = re.compile(r"^-\s*(.+?):\s*(\d+)\s*$")
    for ln in section_lines:
        m = rx.match(ln.strip())
        if m:
            out[m.group(1)] = int(m.group(2))
    return out


def _parse_weakness_line(lines: list[str], prefix: str) -> list[str]:
    for ln in lines:
        if ln.startswith(prefix):
            rhs = ln.split(":", 1)[1].strip()
            items = [x.strip().strip("`") for x in rhs.split(",") if x.strip()]
            return items
    return []


def _color_from_score(score: float) -> str:
    if score >= 0.8:
        return "#1f9d6a"
    if score >= 0.4:
        return "#f0a202"
    return "#d64545"


def _score_chip(score: float) -> str:
    color = _color_from_score(score)
    label = "High" if score >= 0.8 else ("Medium" if score >= 0.4 else "Low")
    return f'<span class="chip" style="background:{color}22;color:{color};border-color:{color}66">{label} {score:.2f}</span>'


def _build_dashboard(markdown_path: Path) -> str:
    lines = _read_lines(markdown_path)
    ranges = _find_section_ranges(lines)

    title = lines[0].lstrip("# ").strip() if lines else "SEPA-Eval Report"

    cap_lines = lines[slice(*ranges.get("## 1. Capability Frontier", (0, 0)))]
    sat_lines = lines[slice(*ranges.get("## 2. Saturation Map", (0, 0)))]
    fail_lines = lines[slice(*ranges.get("## 3. Failure Taxonomy", (0, 0)))]
    sum_lines = lines[slice(*ranges.get("## 4. Evolved Task Summary", (0, 0)))]
    heat_lines = lines[slice(*ranges.get("## 5. Cross-Model Failure Heatmap", (0, 0)))]

    capability = _parse_md_table(cap_lines)
    saturation = _parse_md_table(sat_lines)
    heatmap = _parse_md_table(heat_lines)
    failure_tax = _parse_failure_taxonomy(fail_lines)
    summary = _parse_summary(sum_lines)

    generated_line = ""
    for ln in lines[::-1]:
        if ln.strip().startswith("*Generated by"):
            generated_line = ln.strip().strip("*")
            break

    models = sorted({r["Model"] for r in capability})
    benchmarks = sorted({r["Benchmark"] for r in capability})

    benchmark_model_sr: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for r in capability:
        benchmark_model_sr[r["Benchmark"]][r["Model"]].append(_to_float(r["SR"]))

    benchmark_cards = []
    for bench in benchmarks:
        model_avgs = []
        for m in models:
            vals = benchmark_model_sr[bench][m]
            if vals:
                model_avgs.append((m, sum(vals) / len(vals)))
        model_avgs.sort(key=lambda x: x[1], reverse=True)
        benchmark_cards.append((bench, model_avgs))

    total_tasks = len({r["Task"] for r in capability})
    total_rows = len(capability)
    avg_sr = sum(_to_float(r["SR"]) for r in capability) / total_rows if total_rows else 0.0

    saturated_yes = sum(1 for r in saturation if r.get("Saturated", "").lower() == "yes")
    saturation_rate = saturated_yes / len(saturation) if saturation else 0.0

    disc_vals = [
        (r.get("Task", ""), _to_float(r.get("Disc. Power", "0")), r.get("Benchmark", ""), r.get("Status", ""))
        for r in saturation
    ]
    disc_vals.sort(key=lambda x: x[1], reverse=True)
    top_disc = disc_vals[:8]

    failure_totals: dict[str, int] = {}
    for model_dict in failure_tax.values():
        for k, v in model_dict.items():
            failure_totals[k] = failure_totals.get(k, 0) + v

    max_failure = max(failure_totals.values()) if failure_totals else 1

    weak_a = _parse_weakness_line(heat_lines, "**NeuroVLA-v1.2 only**")
    weak_b = _parse_weakness_line(heat_lines, "**QwenOFT-v2.1 only**")

    heat_rows_html = []
    for r in heatmap:
        task = html.escape(r.get("Task", "").strip("`") )
        m1 = r.get("NeuroVLA-v1.2", "")
        m2 = r.get("QwenOFT-v2.1", "")

        val_re = re.compile(r"([0-9]+\.[0-9]+)")
        m1v = _to_float(val_re.search(m1).group(1)) if val_re.search(m1) else 0.0
        m2v = _to_float(val_re.search(m2).group(1)) if val_re.search(m2) else 0.0

        heat_rows_html.append(
            "<tr>"
            f"<td>{task}</td>"
            f"<td class='score-cell' style='--score:{m1v:.3f}'>{_score_chip(m1v)}</td>"
            f"<td class='score-cell' style='--score:{m2v:.3f}'>{_score_chip(m2v)}</td>"
            "</tr>"
        )

    bench_cards_html = []
    for bench, vals in benchmark_cards:
        bars = []
        for m, sr in vals:
            bars.append(
                "<div class='bar-row'>"
                f"<div class='bar-label'>{html.escape(m)}</div>"
                f"<div class='bar-track'><div class='bar-fill' style='width:{sr * 100:.1f}%'></div></div>"
                f"<div class='bar-val'>{sr:.1%}</div>"
                "</div>"
            )
        bench_cards_html.append(
            "<article class='panel'>"
            f"<h3>{html.escape(bench)}</h3>"
            + "".join(bars)
            + "</article>"
        )

    disc_html = []
    max_disc = max((x[1] for x in top_disc), default=1.0)
    for task, disc, bench, status in top_disc:
        width = 0 if max_disc == 0 else (disc / max_disc * 100)
        disc_html.append(
            "<div class='bar-row'>"
            f"<div class='bar-label'>{html.escape(task)}</div>"
            f"<div class='bar-track'><div class='bar-fill alt' style='width:{width:.1f}%'></div></div>"
            f"<div class='bar-val'>{disc:.3f} <span class='muted'>({html.escape(bench)}, {html.escape(status)})</span></div>"
            "</div>"
        )

    failure_html = []
    for ftype, cnt in sorted(failure_totals.items(), key=lambda x: x[1], reverse=True):
        width = cnt / max_failure * 100
        failure_html.append(
            "<div class='bar-row'>"
            f"<div class='bar-label'>{html.escape(ftype)}</div>"
            f"<div class='bar-track'><div class='bar-fill danger' style='width:{width:.1f}%'></div></div>"
            f"<div class='bar-val'>{cnt}</div>"
            "</div>"
        )

    summary_cards = {
        "Avg SR": f"{avg_sr:.1%}",
        "Tasks Tracked": str(total_tasks),
        "Saturated Tasks": f"{saturated_yes}/{len(saturation)}",
        "Saturation Rate": f"{saturation_rate:.1%}",
        "Seeds Analyzed": str(summary.get("Seeds analyzed", 0)),
        "Tasks Promoted": str(summary.get("Tasks promoted", 0)),
    }

    kpi_html = "".join(
        f"<article class='kpi'><div class='k'>{html.escape(k)}</div><div class='v'>{html.escape(v)}</div></article>"
        for k, v in summary_cards.items()
    )

    weak_html = (
        "<div class='weakness-grid'>"
        "<article class='panel'><h3>Model-specific Weakness: NeuroVLA-v1.2</h3>"
        + ("<ul>" + "".join(f"<li>{html.escape(t)}</li>" for t in weak_a) + "</ul>" if weak_a else "<p class='muted'>None</p>")
        + "</article>"
        "<article class='panel'><h3>Model-specific Weakness: QwenOFT-v2.1</h3>"
        + ("<ul>" + "".join(f"<li>{html.escape(t)}</li>" for t in weak_b) + "</ul>" if weak_b else "<p class='muted'>None</p>")
        + "</article>"
        "</div>"
    )

    return f"""<!doctype html>
<html lang=\"en\">
<head>
  <meta charset=\"utf-8\" />
  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\" />
  <title>{html.escape(title)} Dashboard</title>
  <style>
    :root {{
      --bg: #f7f4ec;
      --paper: #fffaf2;
      --ink: #1d1b18;
      --muted: #6a6257;
      --accent: #0c7c59;
      --accent2: #f08a24;
      --danger: #c44536;
      --line: #e8dcc8;
      --shadow: 0 10px 25px rgba(80, 55, 20, 0.10);
      --radius: 16px;
    }}
    * {{ box-sizing: border-box; }}
    body {{
      margin: 0;
      font-family: 'Avenir Next', 'Segoe UI', sans-serif;
      color: var(--ink);
      background:
        radial-gradient(circle at 10% 0%, #fff9e9 0%, transparent 45%),
        radial-gradient(circle at 100% 10%, #f7e6d7 0%, transparent 35%),
        var(--bg);
      line-height: 1.4;
    }}
    .container {{ max-width: 1200px; margin: 0 auto; padding: 28px 18px 42px; }}
    header {{
      background: linear-gradient(130deg, #1f4037 0%, #3a7d44 55%, #7ac74f 100%);
      color: #fff;
      border-radius: 24px;
      padding: 24px;
      box-shadow: var(--shadow);
    }}
    h1 {{ margin: 0 0 8px; font-size: 30px; letter-spacing: 0.2px; }}
    .sub {{ opacity: 0.92; font-size: 14px; }}
    .kpi-grid {{ display: grid; grid-template-columns: repeat(6, minmax(120px, 1fr)); gap: 10px; margin-top: 18px; }}
    .kpi {{ background: var(--paper); border: 1px solid #f1e6d6; border-radius: 14px; padding: 10px 12px; color: var(--ink); }}
    .kpi .k {{ font-size: 12px; color: var(--muted); text-transform: uppercase; letter-spacing: 0.7px; }}
    .kpi .v {{ font-size: 22px; font-weight: 700; margin-top: 2px; }}
    .section {{ margin-top: 18px; }}
    .section h2 {{ margin: 0 0 10px; font-size: 20px; }}
    .grid-2 {{ display: grid; grid-template-columns: 1fr 1fr; gap: 12px; }}
    .panel {{ background: var(--paper); border: 1px solid var(--line); border-radius: var(--radius); padding: 14px; box-shadow: var(--shadow); }}
    .panel h3 {{ margin: 0 0 10px; font-size: 16px; }}
    .bar-row {{ display: grid; grid-template-columns: 200px 1fr 180px; gap: 10px; align-items: center; margin: 7px 0; }}
    .bar-label {{ font-size: 13px; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }}
    .bar-track {{ width: 100%; height: 12px; border-radius: 999px; background: #efe5d6; overflow: hidden; border: 1px solid #e5d6bf; }}
    .bar-fill {{ height: 100%; background: linear-gradient(90deg, var(--accent), #39a96b); }}
    .bar-fill.alt {{ background: linear-gradient(90deg, #2978a0, #4ca1c9); }}
    .bar-fill.danger {{ background: linear-gradient(90deg, #d64545, #ef8354); }}
    .bar-val {{ font-size: 13px; text-align: right; }}
    .muted {{ color: var(--muted); font-size: 12px; }}
    table {{ width: 100%; border-collapse: collapse; background: var(--paper); border-radius: var(--radius); overflow: hidden; border: 1px solid var(--line); box-shadow: var(--shadow); }}
    th, td {{ padding: 10px; border-bottom: 1px solid #efe3cf; text-align: left; font-size: 13px; }}
    th {{ background: #f4e8d5; font-size: 12px; text-transform: uppercase; letter-spacing: 0.6px; color: #4a443b; }}
    .chip {{ border: 1px solid; border-radius: 999px; padding: 3px 8px; font-size: 12px; font-weight: 600; }}
    .score-cell {{ background: linear-gradient(90deg, rgba(43, 181, 114, calc(var(--score) * 0.35)) 0%, rgba(240, 162, 2, calc((1 - var(--score)) * 0.20)) 100%); }}
    .weakness-grid {{ display: grid; grid-template-columns: 1fr 1fr; gap: 12px; margin-top: 12px; }}
    ul {{ margin: 8px 0 0 18px; padding: 0; }}
    li {{ margin: 4px 0; }}
    footer {{ margin-top: 14px; color: var(--muted); font-size: 12px; text-align: right; }}
    @media (max-width: 1024px) {{
      .kpi-grid {{ grid-template-columns: repeat(3, 1fr); }}
      .grid-2, .weakness-grid {{ grid-template-columns: 1fr; }}
      .bar-row {{ grid-template-columns: 1fr; }}
      .bar-val {{ text-align: left; }}
    }}
    @media (max-width: 640px) {{
      .kpi-grid {{ grid-template-columns: repeat(2, 1fr); }}
      h1 {{ font-size: 24px; }}
    }}
  </style>
</head>
<body>
  <div class=\"container\">
    <header>
      <h1>{html.escape(title)} Dashboard</h1>
      <div class=\"sub\">Quick visual summary for customer demos: benchmark saturation, frontier separation, failure patterns, and promoted evolution tasks.</div>
      <div class=\"kpi-grid\">{kpi_html}</div>
    </header>

    <section class=\"section\">
      <h2>Capability Frontier by Benchmark</h2>
      <div class=\"grid-2\">{''.join(bench_cards_html)}</div>
    </section>

    <section class=\"section\">
      <h2>Saturation and Discriminative Power</h2>
      <div class=\"grid-2\">
        <article class=\"panel\">
          <h3>Most Discriminative Tasks (higher = better model separator)</h3>
          {''.join(disc_html) if disc_html else '<p class="muted">No saturation data found.</p>'}
        </article>
        <article class=\"panel\">
          <h3>Failure Category Intensity (all models)</h3>
          {''.join(failure_html) if failure_html else '<p class="muted">No failure taxonomy data found.</p>'}
        </article>
      </div>
    </section>

    <section class=\"section\">
      <h2>Cross-Model Task Heatmap</h2>
      <table>
        <thead>
          <tr>
            <th>Task</th>
            <th>NeuroVLA-v1.2</th>
            <th>QwenOFT-v2.1</th>
          </tr>
        </thead>
        <tbody>
          {''.join(heat_rows_html)}
        </tbody>
      </table>
      {weak_html}
    </section>

    <footer>{html.escape(generated_line)}</footer>
  </div>
</body>
</html>
"""


def main() -> None:
    parser = argparse.ArgumentParser(description="Render SEPA-Eval markdown report into a polished HTML dashboard.")
    parser.add_argument("--input", default="demo/output/report.md", help="Input markdown report path")
    parser.add_argument("--output", default="demo/output/report.html", help="Output HTML path")
    args = parser.parse_args()

    in_path = Path(args.input)
    out_path = Path(args.output)

    if not in_path.exists():
        raise SystemExit(f"Input report not found: {in_path}")

    html_text = _build_dashboard(in_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(html_text, encoding="utf-8")
    print(f"Rendered dashboard: {out_path}")


if __name__ == "__main__":
    main()
